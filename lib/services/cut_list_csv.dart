/// First line of every cut-list CSV. Older importers strip leading `#` lines,
/// so the schema can evolve without breaking them.
const kCutListCsvCommentLine = '# generated by FitterWelderPro';

/// Localised CSV headers (P1-38). The ASME short-tag in the material column
/// stays unchanged across locales.
///
/// `segment;iso;uwagi` were appended at the END so the positions of the
/// original ten columns (and any spreadsheet built on them) do not move:
///   * segment — the source segment on the saw, `S03`, or `S03 (1/2)` for a
///     part of a cut longer than the stock bar,
///   * iso — the segment's dimension as written on the drawing,
///   * uwagi / note — the extra-weld warning for split cuts.
const kCutListCsvHeaderPl =
    'projekt;materiał;sztanga_mm;rzaz_mm;średnica_mm;ścianka_mm;nr_sztangi;nr_odcinka;cięcie_mm;pozostało_mm;segment;iso;uwagi';
const kCutListCsvHeaderEn =
    'project;material;stock_mm;kerf_mm;diameter_mm;wall_mm;bar_no;piece_no;cut_mm;bar_remaining_mm;segment;iso;note';

/// Quote a CSV/line-tag value if it contains separator chars, quotes, or
/// whitespace. Doubles embedded `"` per RFC 4180 so the same tag round-trips
/// when re-imported into Excel/LibreOffice. Used both for the ASME line-tag
/// chip (defensive — `materialGroup` may someday contain a space) and every
/// CSV cell.
String csvQuote(String raw) {
  if (raw.contains(RegExp(r'[",;\s]'))) {
    final escaped = raw.replaceAll('"', '""');
    return '"$escaped"';
  }
  return raw;
}

/// Free text typed by the user (project name, ISO expression) as a CSV cell.
/// A leading `=`, `+`, `-` or `@` would make Excel/LibreOffice evaluate the
/// cell as a formula (`-80+3000` shows 2920, `=HYPERLINK(…)` runs), so such
/// text gets a leading apostrophe — the spreadsheet convention for "text".
String _csvText(String raw) {
  final safe = raw.startsWith(RegExp(r'[=+\-@]')) ? "'$raw" : raw;
  return csvQuote(safe);
}

/// CSV with one row per cut piece, exactly as CutListSummaryScreen copies it
/// to the clipboard or shares it as a file. Segments are grouped by diameter
/// + wall in the order they arrive and nested into stock bars by
/// [summarizeCutList] — the same function the screen and the PDF use.
///
/// [header] defaults to the PL/EN header picked by [english]; [english] also
/// picks the language of the split-cut warning in the last column.
///
/// Pure function (no I/O, no network) so the export can be checked in tests.
String buildCutListCsv({
  required String projectName,
  required String materialGroup,
  required double stockLengthMm,
  required double sawKerfMm,
  required List<Segment> segments,
  String? header,
  bool english = false,
}) {
  final buf = StringBuffer();
  buf.writeln(kCutListCsvCommentLine);
  buf.writeln(header ?? (english ? kCutListCsvHeaderEn : kCutListCsvHeaderPl));

  final summary = summarizeCutList(
    segments: segments,
    stockLengthMm: stockLengthMm,
    sawKerfMm: sawKerfMm,
  );

  for (final group in summary.groups) {
    for (var i = 0; i < group.plans.length; i++) {
      final b = group.plans[i];
      for (var j = 0; j < b.pieces.length; j++) {
        final piece = b.pieces[j];
        final note = piece.isSplit
            ? oversizeCutWarning(
                piece,
                stockLengthMm: stockLengthMm,
                english: english,
                withLabel: false,
              )
            : '';
        buf.writeln([
          _csvText(projectName),
          csvQuote(materialGroup),
          stockLengthMm.toStringAsFixed(0),
          sawKerfMm.toStringAsFixed(1),
          group.diameterMm.toStringAsFixed(1),
          group.wallMm.toStringAsFixed(1),
          i + 1,
          j + 1,
          piece.lengthMm.toStringAsFixed(0),
          b.remainingMm.toStringAsFixed(0),
          csvQuote(piece.tag ?? ''),
          _csvText(piece.reference ?? ''),
          csvQuote(note),
        ].join(';'));
      }
    }
  }
  return buf.toString();
}

/// ASCII file-name stem from a project name: Polish letters transliterated,
/// everything that is not a letter or digit collapsed to `_`. Keeps share
/// targets (mail clients, Windows shares) from mangling the name.
String cutListFileStem(String projectName) {
  const pl = {
    'ą': 'a', 'ć': 'c', 'ę': 'e', 'ł': 'l', 'ń': 'n', 'ó': 'o', 'ś': 's',
    'ź': 'z', 'ż': 'z', 'Ą': 'A', 'Ć': 'C', 'Ę': 'E', 'Ł': 'L', 'Ń': 'N',
    'Ó': 'O', 'Ś': 'S', 'Ź': 'Z', 'Ż': 'Z',
  };
  final ascii = projectName.split('').map((c) => pl[c] ?? c).join();
  final stem = ascii
      .replaceAll(RegExp(r'[^A-Za-z0-9]+'), '_')
      .replaceAll(RegExp(r'^_+|_+$'), '');
  return stem.isEmpty ? 'projekt' : stem;
}

/// `CutList_<projekt>_<yyyyMMdd-HHmm>.csv`
String cutListCsvFileName(String projectName, DateTime at) {
  String two(int v) => v.toString().padLeft(2, '0');
  final stamp = '${at.year}${two(at.month)}${two(at.day)}-'
      '${two(at.hour)}${two(at.minute)}';
  return 'CutList_${cutListFileStem(projectName)}_$stamp.csv';
}

/// Writes [csv] to [directory]/[fileName] as UTF-8 with a byte-order mark:
/// without the BOM Excel on Windows opens the file as ANSI and shows
/// `materiaĹ‚` instead of `materiał`. The clipboard copy has no BOM.
Future<File> writeCutListCsvFile({
  required Directory directory,
  required String fileName,
  required String csv,
}) async {
  final file = File('${directory.path}${Platform.pathSeparator}$fileName');
  await file.writeAsBytes([0xEF, 0xBB, 0xBF, ...utf8.encode(csv)], flush: true);
  return file;
}

