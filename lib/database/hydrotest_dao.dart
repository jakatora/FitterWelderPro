/// Persistence for hydrostatic pressure tests ("próba ciśnieniowa").
///
/// WHY this file exists: `hydrotest_screen.dart` was ~1080 lines of arithmetic
/// (test pressure, water volume, fill time, minimum hold time) with no way to
/// keep any of it. The calculation died the moment the screen was popped and
/// the only way out was a clipboard copy. A pressure test is an ACCEPTANCE
/// step — ASME B31.3 § 345.2.7 requires records of the tested piping, the test
/// fluid, the test pressure and the date, retained for the owner. A calculator
/// that leaves no record cannot serve that clause, so the numbers had to gain
/// a table.
///
/// SCHEMA OWNERSHIP — read before touching:
/// `hydrotest_records` (and its `idx_hydrotest_created` index) is defined in
/// `lib/database/db.dart` since schema v18, like every other table in
/// `cutlist.db`. It used to be created lazily here, on the first save or
/// read — which meant a phone that had never opened the register had no
/// table, and a backup restored onto it silently dropped every test. A new
/// column goes into `AppDatabase._createTables` plus a migration step
/// (`_ensureColumn`) and a schema version bump, never into this file.
///
/// UNITS — the app's base units, no exceptions:
///   * pressure  → bar     (the screen converts bar/MPa/psi input on the way in)
///   * length    → MILLIMETRES, including the line length the screen collects
///                 in metres; storing metres here would make this the only
///                 table in the app with a different length unit
///   * volume    → litres  (the calculated water fill)
///   * time      → minutes (hold time)
///   * temperature → °C
library;

import '../domain/pressure_test/hydrotest_protocol_meta.dart';
import 'db.dart';

/// Test passed — no leakage, pressure held.
const String kHydrotestPass = 'PASS';

/// Test failed — leak, pressure drop, or the QC engineer rejected it.
const String kHydrotestFail = 'FAIL';

/// Minimum hold time in minutes per ASME B31.3 § 345.2.2(a). Recorded rather
/// than enforced: the app must not decide whether a test is acceptable, but
/// it must be able to point out a hold shorter than the code minimum.
const double kHydrotestMinHoldMinutes = 10.0;

/// Difference below which a start/end pressure delta is gauge noise, not a
/// leak. An analogue manometer on a workshop pump is read to ~0.1 bar; 0.01
/// bar exists only to keep floating-point subtraction from reporting a
/// "drop" of 1e-15 bar on two identical readings.
const double kHydrotestDropEpsilonBar = 0.01;

/// One completed pressure test, exactly as it was witnessed on site.
///
/// Two groups of fields live side by side on purpose:
///   * the WITNESSED half (gauge, start/end pressure, temperature, hold,
///     result, witness) — what actually happened;
///   * the CALCULATED half (od/wall/length/design/factor/test pressure/
///     volume) — the snapshot of the calculator at the moment of saving.
/// The snapshot is copied, not recomputed on read: a protocol printed next
/// year must show the numbers the crew worked to, even if the calculator's
/// defaults have changed since.
///
/// Every numeric field is nullable. A crew that ran the test without a
/// thermometer must still be able to file the record — a half-filled protocol
/// beats no protocol, and an empty cell is honest where a zero would be a lie.
class HydrotestRecord {
  /// uuid v4, generated by the caller (same as the weld journal).
  final String id;

  /// System or line tag under test, e.g. "WFI-101" or "Linia sprężonego powietrza".
  final String systemName;

  /// Test date, ISO `YYYY-MM-DD` — sorts lexicographically, matches the
  /// weld journal's `date` column so the two documents line up in an audit.
  final String date;

  /// Gauge identification: serial number and/or calibration certificate.
  /// ASME B31.3 § 345.5.1 wants a calibrated gauge; the protocol has to name it.
  final String gauge;

  /// Pressure at the start of the hold, in bar.
  final double? pressureStartBar;

  /// Pressure at the end of the hold, in bar.
  final double? pressureEndBar;

  /// Ambient / fluid temperature in °C. Relevant because a 10 K swing moves
  /// the gauge on its own and explains an apparent drop.
  final double? temperatureC;

  /// Hold duration in minutes.
  final double? holdMinutes;

  /// [kHydrotestPass] or [kHydrotestFail]. Never empty — the UI requires an
  /// explicit choice, because the app must not sign off a test by default.
  final String result;

  /// Witness / inspector who was present at the hold.
  final String witness;

  /// Outside diameter in millimetres (calculator snapshot).
  final double? odMm;

  /// Wall thickness in millimetres (calculator snapshot).
  final double? wallMm;

  /// Line length in MILLIMETRES. The screen collects metres; the conversion
  /// happens once, on the way in, so every length in the database keeps the
  /// same unit.
  final double? lineLengthMm;

  /// Design pressure in bar (calculator snapshot).
  final double? designBar;

  /// Effective test factor Pt / P — e.g. 1.8 for ASME B31.3 with ST/S = 1.2
  /// (records filed before the code presets hold the bare multiplier).
  final double? factor;

  /// Test pressure in bar = [designBar] × [factor] (calculator snapshot).
  final double? testPressureBar;

  /// Water volume needed to fill the line, in litres (calculator snapshot).
  final double? volumeL;

  /// Free text: vents used, blinds fitted, why a FAIL was called.
  final String notes;

  /// Protocol fields (company, project, test package, P&ID/ISO, medium, code
  /// preset, stress ratio, metal temperature, gauge range and calibration,
  /// relief valve, protocol no./revision) — schema v19 columns. Empty for
  /// tests filed before v19.
  final HydrotestProtocolMeta meta;

  /// `millisecondsSinceEpoch` of the save. Used for ordering — [date] is the
  /// day of the test and several tests share one day.
  final int createdAt;

  const HydrotestRecord({
    required this.id,
    required this.systemName,
    required this.date,
    required this.result,
    required this.createdAt,
    this.gauge = '',
    this.pressureStartBar,
    this.pressureEndBar,
    this.temperatureC,
    this.holdMinutes,
    this.witness = '',
    this.odMm,
    this.wallMm,
    this.lineLengthMm,
    this.designBar,
    this.factor,
    this.testPressureBar,
    this.volumeL,
    this.notes = '',
    this.meta = const HydrotestProtocolMeta(),
  });

  /// Pressure lost during the hold, in bar; `null` when either reading is
  /// missing. Positive means the line lost pressure.
  double? get pressureDropBar {
    final a = pressureStartBar;
    final b = pressureEndBar;
    if (a == null || b == null) return null;
    return a - b;
  }

  /// True when a real pressure drop was recorded (above gauge noise).
  bool get hasPressureDrop {
    final d = pressureDropBar;
    return d != null && d > kHydrotestDropEpsilonBar;
  }

  /// True when the hold reached the ASME B31.3 minimum. `false` when the hold
  /// time was not recorded at all — an unknown hold cannot be claimed to
  /// satisfy the code.
  bool get meetsMinimumHold {
    final h = holdMinutes;
    return h != null && h >= kHydrotestMinHoldMinutes;
  }

  /// True when the test was signed off as passed.
  bool get passed => result == kHydrotestPass;

  /// Line length in metres, for display only. The stored unit stays mm.
  double? get lineLengthM {
    final mm = lineLengthMm;
    return mm == null ? null : mm / 1000.0;
  }

  Map<String, Object?> toRow() => {
        'id': id,
        'system_name': systemName,
        'test_date': date,
        'gauge': gauge,
        'pressure_start_bar': pressureStartBar,
        'pressure_end_bar': pressureEndBar,
        'temperature_c': temperatureC,
        'hold_minutes': holdMinutes,
        'result': result,
        'witness': witness,
        'od_mm': odMm,
        'wall_mm': wallMm,
        'line_length_mm': lineLengthMm,
        'design_bar': designBar,
        'factor': factor,
        'test_pressure_bar': testPressureBar,
        'volume_l': volumeL,
        'notes': notes,
        'created_at': createdAt,
        ...meta.toRow(),
      };

  /// Reads a row back. Numbers arrive as `num` (SQLite hands back `int` for a
  /// REAL column holding a whole value on some platforms), so every numeric
  /// column goes through `num?` → `toDouble()` instead of a hard `as double`
  /// cast that would throw on `10` but not on `10.5`.
  static HydrotestRecord fromRow(Map<String, Object?> r) => HydrotestRecord(
        id: r['id'] as String,
        systemName: (r['system_name'] as String?) ?? '',
        date: (r['test_date'] as String?) ?? '',
        gauge: (r['gauge'] as String?) ?? '',
        pressureStartBar: _d(r['pressure_start_bar']),
        pressureEndBar: _d(r['pressure_end_bar']),
        temperatureC: _d(r['temperature_c']),
        holdMinutes: _d(r['hold_minutes']),
        result: (r['result'] as String?) ?? kHydrotestFail,
        witness: (r['witness'] as String?) ?? '',
        odMm: _d(r['od_mm']),
        wallMm: _d(r['wall_mm']),
        lineLengthMm: _d(r['line_length_mm']),
        designBar: _d(r['design_bar']),
        factor: _d(r['factor']),
        testPressureBar: _d(r['test_pressure_bar']),
        volumeL: _d(r['volume_l']),
        notes: (r['notes'] as String?) ?? '',
        createdAt: (r['created_at'] as num?)?.toInt() ?? 0,
        meta: HydrotestProtocolMeta.fromRow(r),
      );

  static double? _d(Object? v) => (v as num?)?.toDouble();
}

/// Register of hydrostatic tests. Same shape as the other DAOs in this folder
/// (`AppDatabase.get()` per call, no cached handle) so a reader who knows one
/// knows all of them.
class HydrotestDao {
  static const String table = 'hydrotest_records';

  /// Makes sure the table exists — by opening the database, whose schema
  /// (v18+) defines it. Kept, and kept public, for callers that want to
  /// warm the register up front; it no longer carries any DDL of its own, so
  /// there is exactly one definition of the table in the app.
  Future<void> ensureTable() async {
    await AppDatabase.get();
  }

  Future<void> insert(HydrotestRecord r) async {
    final db = await AppDatabase.get();
    await db.insert(table, r.toRow());
  }

  /// Newest first — a welder opening the register wants the test just filed,
  /// not the one from three weeks ago.
  Future<List<HydrotestRecord>> listAll() async {
    final db = await AppDatabase.get();
    final rows = await db.query(table, orderBy: 'created_at DESC');
    return rows.map(HydrotestRecord.fromRow).toList();
  }

  Future<void> update(HydrotestRecord r) async {
    final db = await AppDatabase.get();
    await db.update(table, r.toRow(), where: 'id = ?', whereArgs: [r.id]);
  }

  Future<void> deleteById(String id) async {
    final db = await AppDatabase.get();
    await db.delete(table, where: 'id = ?', whereArgs: [id]);
  }

  /// Number of filed tests, for the register badge on the calculator screen.
  /// Counted in SQL rather than by reading every row — the badge is rebuilt
  /// on every save and does not need the payload.
  Future<int> count() async {
    final db = await AppDatabase.get();
    final rows = await db.rawQuery('SELECT COUNT(*) AS n FROM $table');
    if (rows.isEmpty) return 0;
    return (rows.first['n'] as num?)?.toInt() ?? 0;
  }
}
