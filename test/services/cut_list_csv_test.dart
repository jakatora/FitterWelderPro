// Trzecia część kroku „Test głównego przebiegu bez sieci”: CSV, które ekran
// CutListSummaryScreen kopiuje do schowka. Test działa przy transporcie HTTP,
// który rzuca błąd i liczy każdą próbę połączenia.
//
// Oczekiwane wiersze policzone ręcznie (sztanga 6000 mm, rzaz 3 mm):
//   sztanga 1: 3293 + 2500, 2 cięcia → 6000 − 5793 − 6 = 201 mm
//   sztanga 2: 1200, 1 cięcie → 6000 − 1200 − 3 = 4797 mm
//   Ø60,3: 700, 1 cięcie → 6000 − 700 − 3 = 5297 mm

import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import 'package:cut_list_app/data/elbow_takeouts.dart';
import 'package:cut_list_app/models/project.dart';
import 'package:cut_list_app/models/segment.dart';
import 'package:cut_list_app/screens/segment_builder_screen.dart';
import 'package:cut_list_app/services/cut_list_csv.dart';
import 'package:cut_list_app/services/iso_parser.dart';

class _OfflineHttpOverrides extends HttpOverrides {
  int connectionAttempts = 0;

  @override
  HttpClient createHttpClient(SecurityContext? context) {
    connectionAttempts++;
    throw const SocketException('offline test: network access is forbidden');
  }
}

Segment _seg(int seqNo, double cutMm,
    {double diameterMm = 114.3, double wallMm = 6.02}) {
  return Segment(
    id: 'seg-$seqNo',
    projectId: 'project-dn100',
    seqNo: seqNo,
    diameterMm: diameterMm,
    wallThicknessMm: wallMm,
    startKind: 'COMPONENT',
    startLibraryId: null,
    startValueMm: 0,
    endKind: 'COMPONENT',
    endLibraryId: null,
    endValueMm: 0,
    isoRef: 'AXIS',
    isoExpr: '',
    isoMm: 0,
    cutMm: cutMm,
    createdAt: 0,
    updatedAt: 0,
  );
}

double _firstCut() {
  final takeout = closestByDn(100).lr90.toDouble();
  final iso = parseIsoExpression('3000+525-80').toDouble();
  return builderCutMm(
    isoMm: iso,
    startRef: IsoRefPoint.axis,
    startOffsetMm: takeout,
    endRef: IsoRefPoint.faceNear,
    endOffsetMm: 0,
    gapMm: 0,
    welds: 2,
  );
}

String _csv(List<Segment> segs,
    {String name = 'Linia DN100', String header = kCutListCsvHeaderPl}) {
  return buildCutListCsv(
    projectName: name,
    materialGroup: 'CS',
    stockLengthMm: 6000,
    sawKerfMm: 3,
    segments: segs,
    header: header,
  );
}

void main() {
  late _OfflineHttpOverrides offline;
  HttpOverrides? previous;

  setUp(() {
    previous = HttpOverrides.current;
    offline = _OfflineHttpOverrides();
    HttpOverrides.global = offline;
  });

  tearDown(() {
    HttpOverrides.global = previous;
  });

  test('3 segmenty DN100 dają dokładne wiersze CSV', () {
    final csv = _csv([
      _seg(1, _firstCut()),
      _seg(2, 2500),
      _seg(3, 1200),
    ]);
    expect(
      csv,
      '# generated by FitterWelderPro\n'
      '$kCutListCsvHeaderPl\n'
      // Kolumny segment;iso;uwagi dopisane na końcu (stare pozycje kolumn
      // bez zmian): etykieta segmentu, wyrażenie ISO (tu puste), uwagi —
      // i za nimi oznaczenie sztuki (v22; tu puste).
      '"Linia DN100";CS;6000;3.0;114.3;6.0;1;1;3293;201;S01;;;\n'
      '"Linia DN100";CS;6000;3.0;114.3;6.0;1;2;2500;201;S02;;;\n'
      '"Linia DN100";CS;6000;3.0;114.3;6.0;2;1;1200;4797;S03;;;\n',
    );
    expect(offline.connectionAttempts, 0);
  });

  test('druga średnica ma własną grupę i numerację sztang', () {
    final csv = _csv([
      _seg(1, 3293),
      _seg(2, 700, diameterMm: 60.3, wallMm: 3.91),
      _seg(3, 2500),
      _seg(4, 1200),
    ]);
    final rows = csv.trimRight().split('\n').skip(2).toList();
    expect(rows, [
      '"Linia DN100";CS;6000;3.0;114.3;6.0;1;1;3293;201;S01;;;',
      '"Linia DN100";CS;6000;3.0;114.3;6.0;1;2;2500;201;S03;;;',
      '"Linia DN100";CS;6000;3.0;114.3;6.0;2;1;1200;4797;S04;;;',
      '"Linia DN100";CS;6000;3.0;60.3;3.9;1;1;700;5297;S02;;;',
    ]);
    expect(offline.connectionAttempts, 0);
  });

  test('nazwa z cudzysłowem jest cytowana wg RFC 4180', () {
    final csv = _csv([_seg(1, 1200)], name: 'Hala "B"');
    final rows = csv.trimRight().split('\n');
    expect(rows.last, '"Hala ""B""";CS;6000;3.0;114.3;6.0;1;1;1200;4797;S01;;;');
    expect(csvQuote('CS'), 'CS');
    expect(csvQuote('a;b'), '"a;b"');
  });

  test('pusty projekt: tylko komentarz i nagłówek', () {
    expect(
      _csv(const []),
      '# generated by FitterWelderPro\n$kCutListCsvHeaderPl\n',
    );
  });

  test('nagłówek EN jest przekazywany bez zmian', () {
    final csv = _csv([_seg(1, 1200)], header: kCutListCsvHeaderEn);
    expect(csv.split('\n')[1],
        'project;material;stock_mm;kerf_mm;diameter_mm;wall_mm;bar_no;piece_no;cut_mm;bar_remaining_mm;segment;iso;note;piece_mark');
    expect(offline.connectionAttempts, 0);
  });

  group('etykiety segmentów i cięcia dłuższe od sztangi', () {
    Segment iso(int seqNo, double cutMm, String isoExpr) {
      final s = _seg(seqNo, cutMm);
      return Segment(
        id: s.id,
        projectId: s.projectId,
        seqNo: s.seqNo,
        diameterMm: s.diameterMm,
        wallThicknessMm: s.wallThicknessMm,
        startKind: s.startKind,
        startLibraryId: s.startLibraryId,
        startValueMm: s.startValueMm,
        endKind: s.endKind,
        endLibraryId: s.endLibraryId,
        endValueMm: s.endValueMm,
        isoRef: s.isoRef,
        isoExpr: isoExpr,
        isoMm: s.isoMm,
        cutMm: s.cutMm,
        createdAt: s.createdAt,
        updatedAt: s.updatedAt,
      );
    }

    test('kolumna iso niesie wyrażenie ISO segmentu (cytowane wg RFC 4180)',
        () {
      final csv = _csv([
        iso(1, 3293, '3000+525-80'),
        iso(2, 1200, '4\'-6"'),
      ]);
      final rows = csv.trimRight().split('\n').skip(2).toList();
      expect(rows, [
        '"Linia DN100";CS;6000;3.0;114.3;6.0;1;1;3293;1501;S01;3000+525-80;;',
        '"Linia DN100";CS;6000;3.0;114.3;6.0;1;2;1200;1501;S02;"4\'-6""";;',
      ]);
    });

    test('tekst zaczynający się od = + - @ nie staje się formułą w Excelu', () {
      final csv = _csv([iso(1, 1200, '-80+3000')], name: '=HYPERLINK("x")');
      final row = csv.trimRight().split('\n').last;
      expect(row,
          '"\'=HYPERLINK(""x"")";CS;6000;3.0;114.3;6.0;1;1;1200;4797;S01;\'-80+3000;;');
    });

    test('7000 mm na sztangach 6000: części S01 (1/2), (2/2) z ostrzeżeniem PL',
        () {
      // Sztanga 1: 6000 bez cięć, reszta 0. Sztanga 2: 4000 + 1000,
      // 2 cięcia → 6000 − 5000 − 6 = 994 mm.
      final csv = _csv([_seg(1, 7000), _seg(2, 4000)]);
      const note = '"odcinek 7000 mm dłuższy niż sztanga 6000 mm — dzielony na '
          '2 części; potrzebna dodatkowa spoina łącząca; uwzględnij gap."';
      final rows = csv.trimRight().split('\n').skip(2).toList();
      expect(rows, [
        '"Linia DN100";CS;6000;3.0;114.3;6.0;1;1;6000;0;"S01 (1/2)";;$note;',
        '"Linia DN100";CS;6000;3.0;114.3;6.0;2;1;4000;994;S02;;;',
        '"Linia DN100";CS;6000;3.0;114.3;6.0;2;2;1000;994;"S01 (2/2)";;$note;',
      ]);
    });

    test('ostrzeżenie w CSV po angielsku, gdy english: true', () {
      final csv = buildCutListCsv(
        projectName: 'Line 7',
        materialGroup: 'SS',
        stockLengthMm: 6000,
        sawKerfMm: 3,
        segments: [_seg(1, 7000)],
        english: true,
      );
      final lines = csv.trimRight().split('\n');
      expect(lines[1], kCutListCsvHeaderEn);
      expect(
        lines[2],
        '"Line 7";SS;6000;3.0;114.3;6.0;1;1;6000;0;"S01 (1/2)";;"piece 7000 mm '
        'is longer than the 6000 mm stock bar — split into 2 parts; an extra '
        'joining weld is needed; allow for the gap.";',
      );
    });
  });

  group('identyfikacja sztuk (v22)', () {
    Segment marked(int seqNo, double cutMm, String? label) {
      final s = _seg(seqNo, cutMm);
      return Segment(
        id: s.id,
        projectId: s.projectId,
        seqNo: s.seqNo,
        diameterMm: s.diameterMm,
        wallThicknessMm: s.wallThicknessMm,
        startKind: s.startKind,
        startLibraryId: s.startLibraryId,
        startValueMm: s.startValueMm,
        endKind: s.endKind,
        endLibraryId: s.endLibraryId,
        endValueMm: s.endValueMm,
        isoRef: s.isoRef,
        isoExpr: s.isoExpr,
        isoMm: s.isoMm,
        cutMm: s.cutMm,
        createdAt: s.createdAt,
        updatedAt: s.updatedAt,
        label: label,
        spoolId: label == null ? null : 'SP02',
      );
    }

    test('oznaczenie sztuki: obok S01 w kolumnie segment i samo na końcu', () {
      final csv = _csv([
        marked(1, 3293, 'SP02-03'),
        marked(2, 2500, null),
        marked(3, 1200, '=SP02-05'),
      ]);
      final rows = csv.trimRight().split('\n').skip(2).toList();
      expect(rows, [
        '"Linia DN100";CS;6000;3.0;114.3;6.0;1;1;3293;201;"S01 SP02-03";;;SP02-03',
        '"Linia DN100";CS;6000;3.0;114.3;6.0;1;2;2500;201;S02;;;',
        // A typed mark is free text: never a formula in Excel.
        '"Linia DN100";CS;6000;3.0;114.3;6.0;2;1;1200;4797;"S03 =SP02-05";;;\'=SP02-05',
      ]);
    });

    test('nagłówek: linia / ISO + rewizja / klient / klasa w linii #', () {
      final csv = buildCutListCsv(
        projectName: 'Linia DN100',
        materialGroup: 'CS',
        stockLengthMm: 6000,
        sawKerfMm: 3,
        segments: [marked(1, 1200, 'SP01-01')],
        identity: const ProjectIdentity(
          lineNo: 'DN100-CWS-1234',
          isoNo: 'ISO-7',
          isoRev: 'B',
          client: 'Orlen',
          spec: 'A1B',
        ),
      );
      final lines = csv.split('\n');
      expect(lines[0], kCutListCsvCommentLine);
      expect(lines[1],
          '# Linia: DN100-CWS-1234 · ISO: ISO-7 rew. B · Klient: Orlen · Klasa: A1B');
      expect(lines[2], kCutListCsvHeaderPl);
      // The data rows keep every column where it was.
      expect(lines[3].split(';'), hasLength(14));
    });

    test('pusta identyfikacja nie dodaje linii', () {
      final csv = buildCutListCsv(
        projectName: 'x',
        materialGroup: 'CS',
        stockLengthMm: 6000,
        sawKerfMm: 3,
        segments: const [],
        identity: ProjectIdentity.empty,
      );
      expect(csv, '# generated by FitterWelderPro\n$kCutListCsvHeaderPl\n');
    });
  });

  group('plik CSV do udostępnienia', () {
    test('nazwa pliku: bez polskich znaków i separatorów ścieżki', () {
      expect(
        cutListCsvFileName('Łącznik żółć / hala 3', DateTime(2026, 9, 24, 13, 5)),
        'CutList_Lacznik_zolc_hala_3_20260924-1305.csv',
      );
      expect(cutListCsvFileName('', DateTime(2026, 1, 2, 3, 4)),
          'CutList_projekt_20260102-0304.csv');
    });

    test('zapis: UTF-8 z BOM (Excel poprawnie czyta „ś” i „ł”)', () async {
      final dir = await Directory.systemTemp.createTemp('fwp-csv-');
      addTearDown(() => dir.delete(recursive: true));
      const csv = 'projekt;materiał\nŁącznik;SS\n';
      final file = await writeCutListCsvFile(
        directory: dir,
        fileName: 'CutList_test.csv',
        csv: csv,
      );
      final bytes = await file.readAsBytes();
      expect(bytes.take(3), [0xEF, 0xBB, 0xBF]);
      expect(utf8.decode(bytes.skip(3).toList()), csv);
      expect(file.path, endsWith('CutList_test.csv'));
    });
  });
}
